-- Original schema, before the exercise metadata upgrade in V2.
CREATE TABLE users (
    id UUID PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    username VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE user_roles (
    user_id UUID NOT NULL REFERENCES users (id),
    role VARCHAR(255) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE training_programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    user_id UUID REFERENCES users (id)
);

CREATE TABLE workouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    training_program_id BIGINT REFERENCES training_programs (id)
);

CREATE TABLE muscle_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    image_url TEXT,
    gif_url TEXT,
    instructions TEXT,
    external_id VARCHAR(255),
    external_source VARCHAR(255)
);

CREATE TABLE exercise_muscle_groups (
    exercise_id BIGINT NOT NULL REFERENCES exercises (id),
    muscle_group_id BIGINT NOT NULL REFERENCES muscle_groups (id),
    PRIMARY KEY (exercise_id, muscle_group_id)
);

CREATE TABLE exercise_equipment (
    exercise_id BIGINT NOT NULL REFERENCES exercises (id),
    equipment_id BIGINT NOT NULL REFERENCES equipment (id),
    PRIMARY KEY (exercise_id, equipment_id)
);

CREATE TABLE workout_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id BIGINT NOT NULL REFERENCES exercises (id),
    workout_id BIGINT REFERENCES workouts (id)
);

CREATE TABLE set_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reps INTEGER NOT NULL,
    kg DOUBLE PRECISION NOT NULL,
    workout_exercise_id BIGINT REFERENCES workout_exercises (id)
);
