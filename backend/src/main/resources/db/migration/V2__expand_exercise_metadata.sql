-- Upgrade the existing schema. Existing installations without Flyway history
-- must be baselined at version 1 before this migration is run.
ALTER TABLE exercise_muscle_groups RENAME TO exercise_primary_muscles;

CREATE TABLE exercise_secondary_muscles (
    exercise_id BIGINT NOT NULL REFERENCES exercises (id),
    muscle_group_id BIGINT NOT NULL REFERENCES muscle_groups (id),
    PRIMARY KEY (exercise_id, muscle_group_id)
);

ALTER TABLE exercises
    ADD COLUMN mechanic VARCHAR(255),
    ADD COLUMN category VARCHAR(255),
    ADD COLUMN level VARCHAR(255);

CREATE TABLE exercise_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(255) NOT NULL UNIQUE,
    url TEXT NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    exercise_id BIGINT REFERENCES exercises (id)
);

CREATE INDEX exercise_images_exercise_id_idx ON exercise_images (exercise_id);

-- Old images have no provider public ID; retain them with a unique legacy ID.
INSERT INTO exercise_images (public_id, url, position, exercise_id)
SELECT 'legacy-exercise-' || id, image_url, 0, id
FROM exercises
WHERE image_url IS NOT NULL;

ALTER TABLE exercises DROP COLUMN image_url;
